import { node, tseslint } from "./eslint/node.js"
import { reactConfig } from "./eslint/react.js"
import { zeroAny } from "./eslint/zero-any.js"

// The Botyard TypeScript standard: eslint/ holds copies of the configs from
// github.com/Botyard-AI/create-botyard-app (tooling/eslint-config). React
// rules for the UI in src/, Node rules for the server, scripts and tests, and
// the "no any" gate everywhere.
export default tseslint.config(
  { ignores: ["dist", "coverage", "eslint"] },
  ...node.map((config) => ({ ...config, ignores: ["src/**", "test/ui/**"] })),
  ...reactConfig.map((config) => ({ ...config, files: ["src/**/*.{ts,tsx}", "test/ui/**/*.tsx"] })),
  ...zeroAny(import.meta.dirname),
  {
    // shadcn/ui components are generated by `npx shadcn add` with several
    // components per file; keep them as upstream writes them.
    files: ["src/components/ui/**"],
    rules: {
      "react-refresh/only-export-components": "off",
    },
  }
)
